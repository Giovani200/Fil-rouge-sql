-- M6.3 Plus sévère que la moyenne ?

WITH notes_avec_moyenne AS (
    SELECT utilisateur_id, film_id, note,
           ROUND(AVG(note) OVER (PARTITION BY film_id), 2) AS moyenne_film
    FROM notes
)
SELECT utilisateurs.pseudo, films.titre, notes_avec_moyenne.note, notes_avec_moyenne.moyenne_film,
       notes_avec_moyenne.note - notes_avec_moyenne.moyenne_film AS ecart
FROM notes_avec_moyenne
JOIN utilisateurs ON utilisateurs.id = notes_avec_moyenne.utilisateur_id
JOIN films ON films.id = notes_avec_moyenne.film_id
WHERE utilisateurs.pseudo = 'nolanfan'
ORDER BY ecart DESC, films.titre;

-- M6.4 Le rythme de visionnage

SELECT journal.date_visionnage, films.titre,
       journal.date_visionnage - LAG(journal.date_visionnage) OVER (ORDER BY journal.date_visionnage, journal.id) AS jours_depuis_precedent
FROM journal
JOIN films ON films.id = journal.film_id
JOIN utilisateurs ON utilisateurs.id = journal.utilisateur_id
WHERE utilisateurs.pseudo = 'cinephile_92'
ORDER BY journal.date_visionnage, journal.id;