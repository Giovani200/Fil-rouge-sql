-- M3.1 La carte de profil

WITH membre AS (
    SELECT id, pseudo FROM utilisateurs WHERE pseudo = 'cinephile_92'
),
nombre_notes AS (
    SELECT COUNT(*) AS nb_films_notes FROM notes
    WHERE utilisateur_id = (SELECT id FROM membre)
),
moyenne_notes AS (
    SELECT ROUND(AVG(note), 2) AS note_moyenne FROM notes
    WHERE utilisateur_id = (SELECT id FROM membre)
),
genre_favori AS (
    SELECT films.genre AS genre_prefere FROM notes
    JOIN films ON films.id = notes.film_id
    WHERE notes.utilisateur_id = (SELECT id FROM membre)
    GROUP BY films.genre
    ORDER BY COUNT(*) DESC, films.genre
    LIMIT 1
),
film_favori AS (
    SELECT films.titre AS coup_de_coeur FROM notes
    JOIN films ON films.id = notes.film_id
    WHERE notes.utilisateur_id = (SELECT id FROM membre)
    ORDER BY notes.note DESC, notes.note_le
    LIMIT 1
)
SELECT membre.pseudo, nombre_notes.nb_films_notes, moyenne_notes.note_moyenne,
       genre_favori.genre_prefere, film_favori.coup_de_coeur
FROM membre
CROSS JOIN nombre_notes
CROSS JOIN moyenne_notes
CROSS JOIN genre_favori
CROSS JOIN film_favori;

