-- M4.2 Toutes les sagas

WITH RECURSIVE episodes AS (
    SELECT films.id, films.saga_id, 1 AS episode, films.titre::TEXT AS parcours FROM films
    WHERE films.saga_id IS NOT NULL AND films.film_precedent_id IS NULL
    UNION ALL
    SELECT films.id, films.saga_id, episodes.episode + 1, episodes.parcours || ' → ' || films.titre FROM films
    JOIN episodes ON films.film_precedent_id = episodes.id
)
SELECT sagas.nom AS saga, episodes.episode, episodes.parcours FROM episodes
JOIN sagas ON sagas.id = episodes.saga_id
ORDER BY saga, episodes.episode;

-- M4.3 Le nombre de Kevin Bacon

WITH RECURSIVE partenaires AS (
    SELECT DISTINCT casting_acteur.personne_id AS acteur_id, casting_partenaire.personne_id AS partenaire_id
    FROM casting AS casting_acteur
    JOIN casting AS casting_partenaire ON casting_partenaire.film_id = casting_acteur.film_id
    WHERE casting_acteur.role = 'acteur'
      AND casting_partenaire.role = 'acteur'
      AND casting_partenaire.personne_id <> casting_acteur.personne_id
),
distances AS (
    SELECT id AS acteur_id, 0 AS degre FROM personnes WHERE nom = 'Kevin Bacon'
    UNION ALL
    SELECT partenaires.partenaire_id, distances.degre + 1 FROM distances
    JOIN partenaires ON partenaires.acteur_id = distances.acteur_id
    WHERE distances.degre < 4
)
SELECT personnes.nom, MIN(distances.degre) AS nombre_de_bacon FROM distances
JOIN personnes ON personnes.id = distances.acteur_id
GROUP BY personnes.id, personnes.nom
ORDER BY nombre_de_bacon DESC, personnes.nom
LIMIT 8;

-- M4.4 D'Omar Sy à Kevin Bacon

WITH RECURSIVE chemins AS (
    SELECT id AS acteur_id, 0 AS degre, nom::TEXT AS chemin, ARRAY[id] AS visites FROM personnes
    WHERE nom = 'Kevin Bacon'
    UNION ALL
    SELECT partenaire.id,
           chemins.degre + 1,
           chemins.chemin || ' — ' || films.titre || ' — ' || partenaire.nom,
           chemins.visites || partenaire.id
    FROM chemins
    JOIN casting AS casting_acteur ON casting_acteur.personne_id = chemins.acteur_id AND casting_acteur.role = 'acteur'
    JOIN casting AS casting_partenaire ON casting_partenaire.film_id = casting_acteur.film_id AND casting_partenaire.role = 'acteur'
    JOIN films ON films.id = casting_acteur.film_id
    JOIN personnes AS partenaire ON partenaire.id = casting_partenaire.personne_id
    WHERE partenaire.id <> ALL (chemins.visites)
      AND chemins.degre < 4
)
SELECT chemins.degre, chemins.chemin FROM chemins
JOIN personnes ON personnes.id = chemins.acteur_id
WHERE personnes.nom = 'Omar Sy'
ORDER BY chemins.degre, chemins.chemin
LIMIT 1;

-- M4.5 Les inaccessibles

WITH RECURSIVE partenaires AS (
    SELECT DISTINCT casting_acteur.personne_id AS acteur_id, casting_partenaire.personne_id AS partenaire_id
    FROM casting AS casting_acteur
    JOIN casting AS casting_partenaire ON casting_partenaire.film_id = casting_acteur.film_id
    WHERE casting_acteur.role = 'acteur'
      AND casting_partenaire.role = 'acteur'
      AND casting_partenaire.personne_id <> casting_acteur.personne_id
),
accessibles AS (
    SELECT id AS acteur_id FROM personnes WHERE nom = 'Kevin Bacon'
    UNION
    SELECT partenaires.partenaire_id FROM accessibles
    JOIN partenaires ON partenaires.acteur_id = accessibles.acteur_id
)
SELECT personnes.nom FROM personnes
WHERE EXISTS (SELECT 1 FROM casting WHERE casting.personne_id = personnes.id AND casting.role = 'acteur')
  AND NOT EXISTS (SELECT 1 FROM accessibles WHERE accessibles.acteur_id = personnes.id)
ORDER BY personnes.nom;

-- M5.1 Top 3 par genre

WITH moyennes AS (
    SELECT films.genre, films.titre, ROUND(AVG(notes.note), 2) AS moyenne FROM films
    JOIN notes ON notes.film_id = films.id
    GROUP BY films.id, films.genre, films.titre
    HAVING COUNT(*) >= 3
),
classement AS (
    SELECT genre, titre, moyenne,
           ROW_NUMBER() OVER (PARTITION BY genre ORDER BY moyenne DESC, titre) AS rang
    FROM moyennes
)
SELECT genre, rang, titre, moyenne FROM classement
WHERE rang <= 3
ORDER BY genre, rang;

-- M5.2 Le classement des réalisateurs

WITH moyennes AS (
    SELECT personnes.nom AS realisateur, ROUND(AVG(notes.note), 2) AS moyenne, COUNT(*) AS nb_notes FROM personnes
    JOIN casting ON casting.personne_id = personnes.id AND casting.role = 'realisateur'
    JOIN notes ON notes.film_id = casting.film_id
    GROUP BY personnes.id, personnes.nom
),
classement AS (
    SELECT DENSE_RANK() OVER (ORDER BY moyenne DESC) AS rang, realisateur, moyenne, nb_notes
    FROM moyennes
)
SELECT rang, realisateur, moyenne, nb_notes FROM classement
WHERE rang <= 10
ORDER BY rang, realisateur;

-- M5.3 Le coup de cœur de chacun

WITH classement AS (
    SELECT utilisateurs.pseudo, films.titre, notes.note, notes.note_le,
           ROW_NUMBER() OVER (PARTITION BY notes.utilisateur_id ORDER BY notes.note DESC, notes.note_le) AS rang
    FROM notes
    JOIN utilisateurs ON utilisateurs.id = notes.utilisateur_id
    JOIN films ON films.id = notes.film_id
)
SELECT pseudo, titre, note, note_le FROM classement
WHERE rang = 1
ORDER BY pseudo;

-- M5.4 Le meilleur épisode

WITH moyennes AS (
    SELECT sagas.nom AS saga, films.titre, ROUND(AVG(notes.note), 2) AS moyenne FROM films
    JOIN sagas ON sagas.id = films.saga_id
    JOIN notes ON notes.film_id = films.id
    GROUP BY sagas.nom, films.id, films.titre
)
SELECT saga, titre, moyenne,
       RANK() OVER (PARTITION BY saga ORDER BY moyenne DESC) AS rang_dans_saga
FROM moyennes
ORDER BY saga, rang_dans_saga, titre;

-- M6.1 Visionnages cumulés

WITH par_mois AS (
    SELECT TO_CHAR(journal.date_visionnage, 'YYYY-MM') AS mois, COUNT(*) AS nb FROM journal
    JOIN utilisateurs ON utilisateurs.id = journal.utilisateur_id
    WHERE utilisateurs.pseudo = 'cinephile_92'
    GROUP BY mois
)
SELECT mois, nb, SUM(nb) OVER (ORDER BY mois) AS cumul FROM par_mois
ORDER BY mois;

-- M6.2 La note d'Inception au fil du temps

SELECT notes.note_le, utilisateurs.pseudo, notes.note,
       ROUND(AVG(notes.note) OVER (ORDER BY notes.note_le ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW), 2) AS moyenne_cumulee
